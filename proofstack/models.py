"""Named, bounded models of tla/RaftStore.tla.

One definition drives both TLC (``python -m proofstack.models cfg NAME`` writes the .cfg)
and the Python explorer (``python -m proofstack.models explore NAME``), so the two tools are
guaranteed to check the same model.  ``xcheck-*`` models are small enough for the Python
explorer; the test suite asserts its distinct-state count equals TLC's.
"""
from __future__ import annotations

import argparse
import sys

from .explore import Bounds, System, bfs
from .raftspec import Flags

BASE = dict(servers=("n1", "n2", "n3"), voters=("n1", "n2", "n3"), MaxTerm=2, MaxLogLen=3,
            MaxValues=1, MaxCrashes=0, MaxReads=0, MaxConfChanges=0, MaxTransfers=0,
            MaxCompactions=0, MaxMsgs=2, MaxSeq=1, PreVote=True, CheckQuorum=True,
            LossyCommit=False, UnsafeCommitAnyTerm=False, SkipTermStartCheck=False, MutNoNoop=False,
            MutVoteAnyLog=False, symmetry=False, simulate=False, sim_traces=0)

MODELS = {
    # --- cross-checked against the Python explorer
    "xcheck-core": dict(servers=("n1", "n2"), voters=("n1", "n2")),
    "xcheck-reads": dict(servers=("n1", "n2"), voters=("n1", "n2"), MaxReads=1, MaxTransfers=1, MaxSeq=2),
    "xcheck-snapshots": dict(servers=("n1", "n2"), voters=("n1", "n2"), MaxValues=2, MaxCrashes=1,
                             MaxCompactions=1, LossyCommit=True),
    "xcheck-membership": dict(servers=("n1", "n2", "n3"), voters=("n1", "n2"), MaxConfChanges=1,
                              MaxLogLen=4, MaxMsgs=2),
    # --- bounded TLC runs reported in the README (three interchangeable voters, symmetry reduction)
    "core3": dict(MaxTerm=3, MaxLogLen=3, MaxValues=1, MaxMsgs=2, MaxSeq=1, MaxCrashes=1, symmetry=True),
    "features3": dict(MaxTerm=3, MaxLogLen=3, MaxValues=1, MaxMsgs=2, MaxSeq=2, MaxReads=1, MaxTransfers=1,
                      MaxCompactions=1, symmetry=True),
    # --- random simulation (no bug expected): deeper behaviours of a bigger model
    "sim-all3": dict(MaxTerm=5, MaxLogLen=6, MaxValues=3, MaxMsgs=6, MaxSeq=6, MaxCrashes=2, MaxReads=2,
                     MaxTransfers=2, MaxCompactions=2, LossyCommit=True, simulate=True, sim_traces=20000),
    # --- mutation runs: each switches on one deliberate bug; TLC is expected to find a counterexample
    "mut-vote-any-log": dict(MaxTerm=3, MaxLogLen=3, MaxMsgs=2, MaxSeq=1, PreVote=False, CheckQuorum=False,
                             MutVoteAnyLog=True, symmetry=True),
    "mut-figure8": dict(MaxTerm=5, MaxLogLen=2, MaxValues=2, MaxMsgs=2, MaxSeq=1, PreVote=False,
                        CheckQuorum=False, MutNoNoop=True, UnsafeCommitAnyTerm=True, symmetry=True),
    "mut-membership": dict(servers=("n1", "n2", "n3", "n4"), voters=("n1", "n2", "n3"), MaxTerm=3,
                           MaxLogLen=4, MaxValues=0, MaxMsgs=2, MaxSeq=1, MaxConfChanges=2, PreVote=False,
                           CheckQuorum=False, SkipTermStartCheck=True),
}

INVARIANTS = ("ElectionSafety LogMatching LeaderCompleteness StateMachineSafety "
              "LinearizableReads NoImplAssertion ConfigMatchesLog IndexSanity")


def model(name):
    m = dict(BASE)
    m.update(MODELS[name])
    return m


def tla_bool(b):
    return "TRUE" if b else "FALSE"


def cfg_text(name) -> str:
    m = model(name)
    consts = {k: v for k, v in m.items() if k[0].isupper()}
    lines = [f"\\* generated by `python -m proofstack.models cfg {name}` -- do not edit",
             "CONSTANTS", "  n1 = n1  n2 = n2  n3 = n3  n4 = n4", "  Nil = Nil",
             "  Server = {" + ", ".join(m["servers"]) + "}",
             "  InitVoters = {" + ", ".join(m["voters"]) + "}"]
    for k, v in consts.items():
        lines.append(f"  {k} = {tla_bool(v) if isinstance(v, bool) else v}")
    lines += ["INIT Init", "NEXT Next", "CONSTRAINT StateConstraint"]
    if m["symmetry"]:
        if set(m["servers"]) != set(m["voters"]) or len(m["servers"]) != 3:
            raise ValueError("symmetry is only defined for three interchangeable voters")
        lines.append("SYMMETRY Symm")
    lines.append("INVARIANTS " + INVARIANTS)
    return "\n".join(lines) + "\n"


def system(name) -> System:
    m = model(name)
    if m["symmetry"]:
        raise ValueError("the Python explorer does not implement symmetry reduction")
    return System(m["servers"], m["voters"],
                  Flags(prevote=m["PreVote"], check_quorum=m["CheckQuorum"], lossy_commit=m["LossyCommit"],
                        unsafe_commit_any_term=m["UnsafeCommitAnyTerm"],
                        skip_term_start_check=m["SkipTermStartCheck"], no_noop=m["MutNoNoop"],
                        vote_any_log=m["MutVoteAnyLog"]),
                  Bounds(max_term=m["MaxTerm"], max_log_len=m["MaxLogLen"], max_values=m["MaxValues"],
                         max_crashes=m["MaxCrashes"], max_reads=m["MaxReads"],
                         max_conf_changes=m["MaxConfChanges"], max_transfers=m["MaxTransfers"],
                         max_compactions=m["MaxCompactions"], max_msgs=m["MaxMsgs"], max_seq=m["MaxSeq"]))


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("cmd", choices=["cfg", "explore", "list"])
    ap.add_argument("name", nargs="?")
    a = ap.parse_args(argv)
    if a.cmd == "list":
        print("\n".join(MODELS))
    elif a.cmd == "cfg":
        sys.stdout.write(cfg_text(a.name))
    else:
        res = bfs(system(a.name))
        print({k: v for k, v in res.items() if k != "violations"},
              "violations:", sorted({v for vs, _ in res["violations"] for v in vs}), flush=True)


if __name__ == "__main__":
    main()
